# Creating a list
fruits = ["Apple", "Banana", "Mango", "Orange"]

print(fruits)

# Accessing elements
print(fruits[0])
print(fruits[2])

# Adding an element
fruits.append("Grapes")
print(fruits)

# Changing an element
fruits[1] = "Pineapple"
print(fruits)

# Removing an element
fruits.remove("Mango")
print(fruits)

# Length of list
print(len(fruits))
